// Generates src/styles/tokens.css from src/theme/lagom.theme.json.
// Every emitted value comes from the captured stylesheet (see theme JSON `evidence`).
import { readFileSync, writeFileSync } from "node:fs";

const theme = JSON.parse(readFileSync("src/theme/lagom.theme.json", "utf8"));
const c = theme.color;
const e = theme.colorExceptions;
const t = theme.typeScale;

const afVars = {
    "af-color-page": c.page,
    "af-color-surface": c.surface,
    "af-color-surface-alt": c.surfaceAlt,
    "af-color-text": c.text,
    "af-color-muted": c.muted,
    "af-color-brand": c.brand,
    "af-color-on-brand": c.onBrand,
    "af-color-border": c.border,
    "af-color-sale": c.sale,
    "af-color-focus": c.focus,
    "af-color-overlay": c.overlay,
    "af-color-error": c.error,
    "af-font-body-family": theme.font.body.family,
    "af-font-body-size": theme.font.body.size,
    "af-font-body-line-height": String(theme.font.body.lineHeight),
    "af-font-display-family": theme.font.display.family,
    "af-layout-container-max": theme.layout.containerMax,
    "af-layout-gutter": theme.layout.gutter,
    "af-layout-header-height": theme.layout.headerHeight,
    "af-motion-easing": theme.motion.easing,
    "af-space-section": theme.space.section,
};

// Reference variable names used verbatim throughout site.css (captured :root).
const refAliases = {
    ink: c.page,
    ink2: e.ink2.value,
    wine: e.wine.value,
    wine2: e.wine2.value,
    gold: c.brand,
    gold2: e.gold2.value,
    ivory: c.surface,
    ivory2: e.ivory2.value,
    text: c.text,
    muted: c.muted,
    "dark-text": e.darkText.value,
    "dark-muted": e.darkMuted.value,
    serif: theme.font.display.family,
    sans: theme.font.body.family,
    gut: theme.layout.gutter,
    max: theme.layout.containerMax,
    ease: theme.motion.easing,
    hdr: theme.layout.headerHeight,
    line: c.border,
    "line-d": e.lineDark.value,
    rose: c.sale,
};

const nonNull = (o) =>
    Object.entries(o).filter(([, v]) => v !== null && v !== undefined);

const out = `/* GENERATED by scripts/generate-tokens.mjs from src/theme/lagom.theme.json.
 * Theme ${theme.name} v${theme.version} — ${theme.verificationStatus}.
 * Do not edit by hand; edit the theme JSON and re-run: pnpm tokens
 */
:root {
${nonNull(afVars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n")}
}
/* Captured reference custom properties (archflowers.com style.css :root), aliased to tokens. */
:root {
${nonNull(refAliases)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n")}
}
body{font-weight:400;font-size:${theme.font.body.size};line-height:${theme.font.body.lineHeight}}
h1{line-height:${theme.font.display.lineHeight}}
.h2{line-height:${t.h2LineHeight}}
.eyebrow{font-size:${t.eyebrow.size};letter-spacing:${t.eyebrow.letterSpacing};font-weight:${t.eyebrow.weight}}
.nav{font-size:${t.nav.size};letter-spacing:${t.nav.letterSpacing}}
.price b{font-size:${t.price.size};font-weight:${t.price.weight};font-variant-numeric:${t.price.numeric}}
.price s{font-size:${t.comparePrice.size}}
.card .code{font-size:${t.cardCode.size};letter-spacing:${t.cardCode.letterSpacing}}
.countdown,.countdown span,.tile-t span{font-size:${t.countdown.size};letter-spacing:${t.countdown.letterSpacing}}
.af-container{width:calc(100% - 2 * var(--gut));max-width:var(--max);margin-inline:auto}
`;

writeFileSync("src/styles/tokens.css", out);
console.log(
    "tokens.css written:",
    nonNull(afVars).length,
    "af tokens,",
    nonNull(refAliases).length,
    "reference aliases",
);
